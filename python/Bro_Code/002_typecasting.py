# typecasting = changing between data types of variable; str(), int(), bool(), float()
name = "Mayank"
age = 19
student = True
marks = 29.4

print(type(marks))
print(marks)

marks += 0.1

print(type(marks))
print(f"{marks}")

marks = int(marks)
print(type(marks))
print(marks)

marks = str(marks)
print(type(marks))
print(marks)

age = float(age)
print(type(age))
print(age)

age = bool(age)
print(type(age))
print(age)

